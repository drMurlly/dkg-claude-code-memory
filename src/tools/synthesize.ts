/**
 * Synthesize tool — create knowledge synthesis from session artifacts.
 */

import type { ToolDeps, ToolResult, SynthesizeParams } from './types.js';
import type { ArtifactStatus } from '../types/artifact.js';
import { handleSearch } from './search.js';
import { handleCapture } from './capture.js';

/**
 * Handle synthesize tool invocation.
 */
export async function handleSynthesize(
  params: SynthesizeParams,
  deps: ToolDeps,
): Promise<ToolResult> {
  const { sessionId, title } = params;

  // Validate sessionId
  if (!sessionId || sessionId.trim().length === 0) {
    return {
      success: false,
      message: 'sessionId is required',
    };
  }

  // Fetch all session artifacts (no limit)
  const searchResult = await handleSearch({ sessionId, limit: 1000 }, deps);

  if (!searchResult.success) {
    return {
      success: false,
      message: `Failed to fetch session artifacts: ${searchResult.message}`,
    };
  }

  const artifacts = searchResult.artifacts as Array<{
    id: string;
    name: string;
    type: string;
    status: string;
    contentHash: string;
  }>;

  if (artifacts.length === 0) {
    return {
      success: false,
      message: `No artifacts found for session: ${sessionId}`,
    };
  }

  // Build synthesis text
  const typeCounts: Record<string, number> = {};
  for (const a of artifacts) {
    const t = a.type ?? 'unknown';
    typeCounts[t] = (typeCounts[t] ?? 0) + 1;
  }

  const typeBreakdown = Object.entries(typeCounts)
    .map(([type, count]) => `${type}: ${count}`)
    .join(', ');

  const artifactList = artifacts
    .map((a) => `- ${a.name ?? a.id} (${a.type}, ${a.status}, hash: ${a.contentHash?.slice(0, 8) ?? 'N/A'})`)
    .join('\n');

  const synthesisText = `## Knowledge Synthesis for Session: ${sessionId}

**Artifact Count:** ${artifacts.length}

**Type Breakdown:** ${typeBreakdown}

### Artifacts:
${artifactList}

---
*Generated by dkg-claude-code-memory synthesis tool*
`;

  // Use custom title if provided, otherwise use auto-generated title (B4 fix)
  const captureTitle = title ?? `Synthesis: ${sessionId}`;

  // Capture the synthesis as a new artifact
  const captureResult = await handleCapture({
    content: synthesisText,
    artifactType: 'knowledge_synthesis',
    title: captureTitle,
    status: 'validated' as ArtifactStatus,
    sessionId,
    source: 'tool',
  }, deps);

  if (!captureResult.success) {
    return {
      success: false,
      message: `Failed to capture synthesis: ${captureResult.message}`,
    };
  }

  return {
    success: true,
    message: 'Knowledge synthesis created successfully',
    synthesisArtifactId: captureResult.artifactId as string,
    ual: captureResult.ual as string,
    artifactCount: artifacts.length,
    synthesis: synthesisText,
  };
}
